// SDK-free host assembly, not the authority GameSession. Actual separate
// owned subobjects keep UI/audio/transport/cache/observer/task state outside
// GameSession. Native and independent hosts still require the same real
// production stages with separate authority and host ownership.
struct RuntimeProductionHostState : RuntimeGameSessionState, RuntimeHostNetworkRoutingState, RuntimeHostLocalPresentationState, RuntimeHostAudioState, RuntimeHostResourceCacheState, RuntimeHostPathTaskState, RuntimeHostObservabilityState {
    RuntimeProductionHostState(const RuntimeUiClock& ui,const RuntimeUiClock& audio,RuntimeSessionGeometry* presentation=nullptr) noexcept(false)
        :uiClock(&ui),worldAudioClock(&audio),constructionUiClock(&ui),constructionAudioClock(&audio),geometry(presentation) {}
    // Staged authority can own the complete Native host in its lifetime contracts.
    virtual ~RuntimeProductionHostState() = default;
    const RuntimeUiClock* uiClock = nullptr;
    const RuntimeUiClock* worldAudioClock = nullptr;
    const RuntimeUiClock* constructionUiClock=nullptr;
    const RuntimeUiClock* constructionAudioClock=nullptr;
    RuntimeSessionGeometry* geometry=nullptr;
    RuntimeSessionPrewarmMerge* prewarmMerge=nullptr;
};
