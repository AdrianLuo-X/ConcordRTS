#pragma once

#include "RuntimeInternetConnectivity.h"

#include <cstddef>
#include <cstdint>
#include <functional>
#include <memory>
#include <string>
#include <vector>

// The coordinator is deliberately transport-agnostic. A deployment adapter
// supplies mutually authenticated coordinator/relay channels, the advertised
// relay endpoints, a monotonic clock, and cryptographically secure random
// bytes. No public Concord service or address is embedded in the runtime.
inline constexpr std::size_t runtimeInternetCoordinatorHardMaximumRooms = 128;
inline constexpr std::size_t runtimeInternetCoordinatorHardMaximumConnections = 4096;
inline constexpr std::size_t runtimeInternetCoordinatorHardMaximumConnectionsPerRoom = 64;
inline constexpr std::size_t runtimeInternetCoordinatorHardMaximumSpectatorsPerRoom = 32;
inline constexpr std::size_t runtimeInternetCoordinatorHardMaximumConnectionsPerPeer = 16;
inline constexpr std::size_t runtimeInternetCoordinatorHardMaximumRelayRoutes = 4096;
inline constexpr std::size_t runtimeInternetCoordinatorHardMaximumReplayTombstones = 8192;
inline constexpr std::size_t runtimeInternetCoordinatorMaximumAdmissionProofBytes = 512;

enum class RuntimeInternetServiceChannel : std::uint8_t {
    CoordinatorTls = 1,
    RelayUdp = 2,
    RelayTcp = 3
};

// authenticatedPeerId/authenticatedServiceId must come from the deployment
// adapter's authenticated channel, never from the packet's claimed envelope.
struct RuntimeInternetServiceEnvelope {
    RuntimeInternetServiceChannel channel =
        RuntimeInternetServiceChannel::CoordinatorTls;
    std::string authenticatedServiceId;
    std::string authenticatedPeerId;
    // Optional password metadata for protected rooms: a host verifier on
    // RegisterRoom or a peer-bound proof on JoinRoom. It stays outside the
    // legacy control packet and is bound to the mutually authenticated peer.
    std::vector<std::uint8_t> roomAdmissionProof;
    RuntimeNetworkPacket packet;
};

enum class RuntimeInternetCoordinatorActionKind : std::uint8_t {
    SendCoordinator = 1,
    SendRelay = 2,
    ActivateRelayRoute = 3,
    DeactivateRelayRoute = 4
};

// SendCoordinator is delivered on the target peer's authenticated service
// channel. SendRelay is delivered on relayTransport at relayEndpoint.
// Activate/DeactivateRelayRoute let an external data-plane adapter start or
// stop forwarding opaque game packets for the two authenticated peers.
struct RuntimeInternetCoordinatorAction {
    RuntimeInternetCoordinatorActionKind kind =
        RuntimeInternetCoordinatorActionKind::SendCoordinator;
    std::string targetPeerId;
    RuntimeInternetRelayTransport relayTransport =
        RuntimeInternetRelayTransport::Udp;
    RuntimeInternetEndpoint relayEndpoint;
    RuntimeNetworkPacket packet;
    std::uint64_t connectionId = 0;
    std::string roomId;
    std::string hostPeerId;
    std::string remotePeerId;
    RuntimeInternetRole remoteRole = RuntimeInternetRole::Client;
    std::uint64_t expiresAtMilliseconds = 0;
};

struct RuntimeInternetCoordinatorConfig {
    std::string serviceId;
    RuntimeInternetEndpoint udpRelayEndpoint;
    RuntimeInternetEndpoint tcpRelayEndpoint;

    std::uint32_t roomLeaseMilliseconds = 10000;
    std::uint32_t connectionLeaseMilliseconds = 30000;
    std::uint32_t relayLeaseMilliseconds = 30000;
    std::uint32_t replayRetentionMilliseconds = 60000;
    std::uint32_t reconnectGraceMilliseconds = 30000;

    std::size_t maximumRooms = runtimeInternetMaximumRooms;
    std::size_t maximumRoomsPerPeer = 4;
    std::size_t maximumConnections = 1024;
    std::size_t maximumConnectionsPerRoom = 31;
    std::size_t maximumSpectatorsPerRoom = 8;
    // A full 8-combatant + 8-spectator room has 15 remote routes owned by
    // its host account. Keep one additional slot so role/room limits, rather
    // than this shared host quota, produce the canonical full-room rejection.
    std::size_t maximumConnectionsPerPeer = 16;
    std::size_t maximumRelayRoutes = 512;
    // Each active connection reserves one future tombstone slot. Therefore
    // this limit must be at least maximumConnections.
    std::size_t maximumReplayTombstones = 2048;

    std::size_t connectionTokenBytes = 32;
    std::size_t relayTicketBytes = 32;

    // Both callbacks are required. The clock must be monotonic. Random bytes
    // must be generated by a CSPRNG in production; deterministic generators
    // are intended only for repeatable tests.
    std::function<std::uint64_t()> nowMilliseconds;
    std::function<bool(std::uint8_t*, std::size_t)> secureRandomBytes;
    std::function<bool(
        const std::string& roomId,
        const std::string& authenticatedPeerId,
        const std::vector<std::uint8_t>& proof
    )> authorizePasswordJoin;
};

class RuntimeInternetCoordinator {
public:
    RuntimeInternetCoordinator();
    ~RuntimeInternetCoordinator();
    RuntimeInternetCoordinator(RuntimeInternetCoordinator&&) noexcept;
    RuntimeInternetCoordinator& operator=(RuntimeInternetCoordinator&&) noexcept;
    RuntimeInternetCoordinator(const RuntimeInternetCoordinator&) = delete;
    RuntimeInternetCoordinator& operator=(const RuntimeInternetCoordinator&) = delete;

    bool open(
        RuntimeInternetCoordinatorConfig config,
        std::string& errorMessage
    );

    // Decodes one canonical control packet, binds it to the authenticated
    // service/peer identity, updates authoritative state atomically, and emits
    // adapter actions. On failure no request-specific state is committed.
    bool receive(
        const RuntimeInternetServiceEnvelope& envelope,
        std::vector<RuntimeInternetCoordinatorAction>& actions,
        std::string& errorMessage
    );

    // Final coordinator-account cleanup. The deployment adapter first uses
    // retainRunningPeerForReconnect() for an unexpected running-match loss;
    // it calls this only when no retention applies or that deadline expires.
    bool authenticatedPeerDisconnected(
        const std::string& authenticatedServiceId,
        const std::string& authenticatedPeerId,
        std::vector<RuntimeInternetCoordinatorAction>& actions,
        std::string& errorMessage
    );
    // Keeps only an already sealed combatant session while the same account
    // reauthenticates. Returns zero when no running session can be retained.
    std::uint64_t retainRunningPeerForReconnect(
        const std::string& authenticatedServiceId,
        const std::string& authenticatedPeerId);
    bool hasPendingReconnect(const std::string& authenticatedServiceId,
        const std::string& authenticatedPeerId) const;

    // Data-plane adapters call these only with identities obtained from the
    // authenticated relay channel. A heartbeat extends the active route;
    // channel closure revokes the old relay immediately. A sealed combatant
    // keeps a bounded identity record for ResumeRoute; other routes are removed.
    bool touchRelayRoute(
        std::uint64_t connectionId,
        RuntimeInternetRelayTransport transport,
        const std::string& authenticatedServiceId,
        const std::string& authenticatedPeerId,
        std::vector<RuntimeInternetCoordinatorAction>& actions,
        std::string& errorMessage
    );
    bool relayChannelClosed(
        std::uint64_t connectionId,
        RuntimeInternetRelayTransport transport,
        const std::string& authenticatedServiceId,
        const std::string& authenticatedPeerId,
        std::vector<RuntimeInternetCoordinatorAction>& actions,
        std::string& errorMessage
    );

    // Expires room, connection, replay, and relay leases using the injected
    // clock. Active relay expirations produce DeactivateRelayRoute actions.
    std::vector<RuntimeInternetCoordinatorAction> poll();

    void close();
    bool isOpen() const;
    std::size_t roomCount() const;
    std::size_t connectionCount() const;
    std::size_t relayRouteCount() const;

private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};
